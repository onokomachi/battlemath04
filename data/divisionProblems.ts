/**
 * data/divisionProblems.ts — 単元「わり算の筆算(÷1けた)」「わり算の筆算(÷2けた)」
 * wari-hissann3 の問題項目粒度(MENTAL/RULES/ESTIMATE/CHECK/WORDの26項目)に
 * 合わせて再構成。1項目=1つの狭いスキルに絞ることで、授業で新しく習った
 * 内容だけを反復練習できるようにする。
 * あまりのある答えは「24あまり3」形式(キーパッドに「あまり」キー)。
 */
import type { Problem } from '../types';
import { toGuidedRetryHint } from '../utils/toGuidedRetryHint';

interface TextExtra {
  svg?: string;
  options?: string[];
  multiple?: boolean;
  hint?: string | string[];
}

const t = (question: string, answer: string, extra?: TextExtra): Problem => ({
  type: 'text',
  data: { question, ...extra },
  answer,
});

const divAns = (a: number, b: number): string => {
  const q = Math.floor(a / b);
  const r = a % b;
  return r === 0 ? String(q) : `${q}あまり${r}`;
};

const divHint = (a: number, b: number): string[] => {
  const q = Math.floor(a / b);
  const r = a % b;
  return [
    'たてる → かける → ひく → おろす の じゅんばんで 筆算しよう。',
    r === 0 ? `${b} × ${q} = ${a} で わり切れるね。` : `${b} × ${q} = ${b * q}、${a} − ${b * q} = ${r}。答えは ${q}あまり${r} だね。`,
  ];
};

/**
 * wari-hissann3 の筆算シミュレーター(位取り選択→たてる→かける→ひく→おろす、
 * 仮商のやり直し)をそのまま起動する guided 問題を作る。
 */
const guided = (a: number, b: number, opts?: { zeroFocus?: boolean; zeroShortcut?: boolean }): Problem => ({
  type: 'guided',
  data: {
    guidedKind: 'division-hissan',
    question: `${a} ÷ ${b} の筆算をしましょう。`,
    dividend: a,
    divisor: b,
    zeroFocus: opts?.zeroFocus,
    zeroShortcut: opts?.zeroShortcut,
  },
  answer: divAns(a, b),
});

