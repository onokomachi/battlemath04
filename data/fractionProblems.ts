/**
 * data/fractionProblems.ts — 小4「分数」全単元の問題データ
 *
 * 東京書籍『新編 新しい算数 4下』⑩「分数をくわしく調べよう」(全8時間)の展開に準拠し、
 * 第3学年の既習事項を足場(復習)として含む。設計根拠は docs/DESIGN.md を参照。
 *
 * 表記の規約:
 *  - 問題文・選択肢内の分数は {3/4} {2と1/3} のマークアップで書く(FractionText が積み上げ表記に描画)
 *  - 解答は "3/4" / "2と1/3" / "3" 形式(utils/fraction.ts の分数採点器が判定)
 *  - data.requireForm: 'mixed'(帯分数のみ正答) | 'improper'(仮分数のみ) | 'integer'(整数のみ)
 *    未指定は「値が等しく分母が同じ表現」をすべて正答(例: 7/5 と 1と2/5)
 *
 * 問題はすべて決定的(乱数なし)。カードバトルPvPで全クライアントの
 * CARD_DEFINITIONS が一致することを保証する。
 */
import type { Problem } from '../types';
import { numberLineSvg, stackedNumberLinesSvg, literSvg, tapeSvg } from '../utils/fractionSvg';

interface TextExtra {
  svg?: string;
  options?: string[];
  multiple?: boolean;
  requireForm?: 'mixed' | 'improper' | 'integer';
  hint?: string | string[];
}

const t = (question: string, answer: string, extra?: TextExtra): Problem => ({
  type: 'text',
  data: { question, ...extra },
  answer,
});

