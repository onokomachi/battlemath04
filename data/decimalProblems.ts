interface TextExtra {
  svg?: string;
  options?: string[];
  multiple?: boolean;
  hint?: string | string[];
}

const t = (question: string, answer: string, extra?: TextExtra): Problem => ({
  type: 'text',
  data: { question, ...extra },
  answer,
});

const fmt = (n: number): string => {
  // 浮動小数の誤差を避けて 0.001 単位で丸める
  return String(Math.round(n * 1000) / 1000);
};

/** 小数の小数点以下けた数(1.36 → 2, 8 → 0) */
const decPlaces = (n: number): number => {
  const s = n.toString();
  const i = s.indexOf('.');
  return i < 0 ? 0 : s.length - i - 1;
};

/** syo4-syousu の DecimalAddSubModule/DecimalMulDivModule(小数点をそろえる筆算ビルダー)を起動する guided 問題 */
const guidedDecimal = (a: number, b: number, operator: '+' | '-' | '×' | '÷'): Problem => {
  const raw = operator === '+' ? a + b : operator === '-' ? a - b : operator === '×' ? a * b : a / b;
  return {
    type: 'guided',
    data: {
      guidedKind: operator === '+' || operator === '-' ? 'decimal-addsub' : 'decimal-muldiv',
      question: `${a} ${operator} ${b} の筆算をしましょう。`,
      operator,
      a,
      b,
    },
    answer: fmt(raw),
  };
};

