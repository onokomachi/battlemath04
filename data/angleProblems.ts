/**
 * data/angleProblems.ts — 単元「角の大きさ」(東書4上④)
 *
 * 学習アプリの性質上、分度器での実測・作図はできないため出題しない。
 * かわりにテスト頻出の以下の形式を厚くする:
 *  - 三角じょうぎ2まいの角の知識(90°,60°,30° / 90°,45°,45°)
 *  - 三角じょうぎを組み合わせた・重ねた角の計算(75°,105°,135°,15°など)
 *  - 直角何こ分・1回転/半回転などの角の量感
 *  - 見当づけ(直角とくらべて大きい/小さい) — 実測せず判断できる2択
 *  - 180°をこえる角は「のこりの角」を問題文で示し、計算で求める形式
 */
import type { Problem } from '../types';
import { angleSvg, crossingLinesSvg, sankakuJougiSvg, straightLineAngleSvg } from '../utils/mathSvg';

interface TextExtra {
  svg?: string;
  options?: string[];
  multiple?: boolean;
  hint?: string | string[];
}

const t = (question: string, answer: string, extra?: TextExtra): Problem => ({
  type: 'text',
  data: { question, ...extra },
  answer,
});

// ---- 交わる直線の角(となり合う角・向かい合う角) ----
const majiwaru: Problem[] = [
  ...([
    [140, true, 40], [140, false, 140], [120, true, 60], [60, false, 60], [110, true, 70], [75, false, 75],
    [100, true, 80], [100, false, 100], [130, true, 50], [130, false, 130], [150, true, 30], [150, false, 150],
    [95, true, 85], [95, false, 95], [65, true, 115], [65, false, 65], [125, true, 55], [125, false, 125],
  ] as const).map(
    ([given, adjacent, ans]) =>
      t(`2本の直線が 交わっています。${given}°の角の ${adjacent ? 'となり' : '向かい'}にある「あ」の角度は 何度ですか。`, String(ans), {
        svg: crossingLinesSvg(given, adjacent),
        hint: adjacent
          ? ['一直線の角は 180°だよ。', `180 − ${given} = ${ans}。となり合う角と あわせて 180°だね。`]
          : ['向かい合う角(対頂角)は 同じ大きさだよ。', `だから ${ans}°だね。`],
      }),
  ),
  t('1回転の角は 何度ですか。', '360', {
    hint: ['ぐるっと 1回転で 360°。半回転(一直線)は 180°だね。'],
  }),
  t('半回転(一直線)の角は 何度ですか。', '180', {
    hint: ['1回転(360°)の 半分だよ。'],
  }),
];

