const makeRangeProblems = (
  tuples: readonly (readonly [number, number, number])[],
  placeLabel: string,
): Problem[] =>
  tuples.flatMap(([target, min, max], i) => {
    const correct = `${min}以上${max}以下`;
    const distractorsAll = [`${min}以上${max + 1}以下`, `${min - 1}以上${max}以下`, `${min + 1}以上${max + 1}以下`];
    const rangeProblem = t(
      `四捨五入して ${placeLabel}までの がい数にしたとき ${target}になる 整数の はんいは どれですか。`,
      correct,
      {
        options: [correct, distractorsAll[i % 3], distractorsAll[(i + 1) % 3]],
        hint: [`${target}に なる いちばん小さい数と いちばん大きい数を かんがえよう。`, `はんいは「${correct}」だね。`],
      },
    );
    const minMaxProblem = i % 2 === 0
      ? t(`四捨五入して ${placeLabel}までの がい数にしたとき ${target}になる 整数のうち、いちばん小さい数は いくつですか。`, String(min), {
          hint: [`${placeLabel}の 一つ下の位を 四捨五入して ${target}に なる、いちばん小さい数を かんがえよう。`],
        })
      : t(`四捨五入して ${placeLabel}までの がい数にしたとき ${target}になる 整数のうち、いちばん大きい数は いくつですか。`, String(max), {
          hint: [`${max + 1}に なると 上の位が くり上がって ${target}では なくなるね。`, `だから ${max}が いちばん大きいよ。`],
        });
    return [rangeProblem, minMaxProblem];
  });

